// Account data (ADR 0003): one JSON file per account, `accounts/<id>.json` in the data
// folder, holding a revision number and the stored task and label documents as sent.
// Updates for one account run one at a time, so each checked save is a single step.
// Files are written whole (see Files), so a crash never leaves half a file.

/** The file operations the store needs; main.ts gives it the real disk. */
export interface Files {
  /** The file's text, or null when it does not exist. */
  read(path: string): Promise<string | null>;
  /** Replaces the file in one step (write a temporary file, then rename it). */
  writeWhole(path: string, text: string): Promise<void>;
}

/** One account's stored documents by id. The handler checks them with core's parsers. */
export interface AccountData {
  revision: number;
  tasks: Record<string, unknown>;
  labels: Record<string, unknown>;
}

/** What an update returns: whether it changed the data (so it is written), and a value. */
export interface UpdateResult<T> {
  readonly changed: boolean;
  readonly value: T;
}

/** Account ids are generated by the server (accounts.ts), so anything else is refused. */
const ID_PATTERN = /^[0-9a-f]{32}$/;

/** Reads and updates account data under `dir`. */
export function createStore(files: Files, dir: string) {
  /** The last queued update per account; the next one waits for it. */
  const queues = new Map<string, Promise<unknown>>();

  const pathOf = (accountId: string): string => {
    if (!ID_PATTERN.test(accountId)) throw new Error("Bad account id.");
    return `${dir}/accounts/${accountId}.json`;
  };

  async function load(accountId: string): Promise<AccountData> {
    const text = await files.read(pathOf(accountId));
    if (text === null) {
      return { revision: 0, tasks: emptyRecord(), labels: emptyRecord() };
    }
    // A corrupt file is an error to look at, never a reason to start empty.
    const doc: unknown = JSON.parse(text);
    if (
      typeof doc !== "object" ||
      doc === null ||
      !("revision" in doc) ||
      typeof doc.revision !== "number" ||
      !("tasks" in doc) ||
      typeof doc.tasks !== "object" ||
      doc.tasks === null ||
      !("labels" in doc) ||
      typeof doc.labels !== "object" ||
      doc.labels === null
    ) {
      throw new Error(`Data file for ${accountId} is malformed.`);
    }
    return {
      revision: doc.revision,
      tasks: Object.assign(emptyRecord(), doc.tasks),
      labels: Object.assign(emptyRecord(), doc.labels),
    };
  }

  return {
    /** The account's data now (an empty account is revision 0). */
    async read(accountId: string): Promise<AccountData> {
      pathOf(accountId);
      // Wait for a running update, whether it succeeded or not.
      await queues.get(accountId)?.catch(() => undefined);
      return load(accountId);
    },

    /**
     * Runs `change` on the account's data after any earlier update for the account,
     * then writes the file and raises the revision if it changed anything.
     */
    async update<T>(
      accountId: string,
      change: (data: AccountData) => UpdateResult<T>,
    ): Promise<T> {
      const path = pathOf(accountId);
      const previous = queues.get(accountId) ?? Promise.resolve();
      const run = previous
        .catch(() => undefined)
        .then(async () => {
          const data = await load(accountId);
          const result = change(data);
          if (result.changed) {
            data.revision += 1;
            await files.writeWhole(path, JSON.stringify(data));
          }
          return result.value;
        });
      queues.set(accountId, run);
      return await run;
    },
  };
}

/** The store's handle. */
export type Store = ReturnType<typeof createStore>;

/**
 * A record with no prototype, so a stored key such as "__proto__" is only ever data.
 * The handler also allows only letters, digits and dashes in ids.
 */
function emptyRecord(): Record<string, unknown> {
  return Object.create(null) as Record<string, unknown>;
}
